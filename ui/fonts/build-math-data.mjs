/* node ui/fonts/build-math-data.mjs: writes ui/fonts/math-data.js, KaTeX's stylesheet with its twenty fonts inlined as woff2 data: URIs (#996),
   from the KaTeX the app already bundles (node_modules/katex, the same version as the renderer, so the glyph metrics always match). A plain JS
   string, so no bundler needs a loader for font or CSS files, and DSH, which serves a plugin's client.*.js chunks only, needs no other file.
   The woff and ttf fallbacks are left out (every browser that runs StudyHub reads woff2) and `font-display: block` becomes `swap`: a formula
   shows at once in the fallback serif and never holds back the page. tests/math-font.test.mjs checks that the module never drifts from this.
   To update: update katex, run this. The licence (KaTeX, MIT) is ui/fonts/KaTeX-LICENSE.txt, a copy of node_modules/katex/LICENSE. */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const KATEX = new URL('../../node_modules/katex/', import.meta.url);
const FACES = 20;
const SOURCE = /src: url\(fonts\/([A-Za-z0-9_-]+)\.woff2\) format\("woff2"\), url\(fonts\/\1\.woff\) format\("woff"\), url\(fonts\/\1\.ttf\) format\("truetype"\);/g;

/** The text of ui/fonts/math-data.js. */
export async function mathDataSource() {
  const { version } = JSON.parse(await readFile(new URL('package.json', KATEX), 'utf8'));
  const css = await readFile(new URL('dist/katex.css', KATEX), 'utf8');
  const names = [...css.matchAll(SOURCE)].map((match) => match[1]);
  if (names.length !== FACES || (css.match(/@font-face/g) || []).length !== FACES) throw new Error(`katex.css ${version}: expected ${FACES} faces in the known form`);
  const data = new Map(await Promise.all(names.map(async (name) => [name, (await readFile(new URL(`dist/fonts/${name}.woff2`, KATEX))).toString('base64')])));
  const inlined = css.replace(SOURCE, (_, name) => `src: url(data:font/woff2;base64,${data.get(name)}) format("woff2");`)
    .replace(/font-display: block;/g, 'font-display: swap;');
  const { code } = await transform(inlined, { loader: 'css', minify: true, legalComments: 'none' });
  return `/*! KaTeX ${version} stylesheet and fonts (MIT, ui/fonts/KaTeX-LICENSE.txt; Copyright (c) 2013-2020 Khan Academy and other contributors). */
/* GENERATED by ui/fonts/build-math-data.mjs from node_modules/katex. Do not edit. Only ui/study-math-render.js imports it. */
export default ${JSON.stringify(code.trim())};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = await mathDataSource();
  await writeFile(new URL('./math-data.js', import.meta.url), source);
  console.log(`ui/fonts/math-data.js written (${source.length} characters)`);
}
