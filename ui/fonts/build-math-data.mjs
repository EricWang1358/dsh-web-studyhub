/* node ui/fonts/build-math-data.mjs: writes the two modules a formula is drawn with (#996), from the KaTeX the app already bundles (node_modules/katex,
   the same version as the renderer, so the glyph metrics always match). Each is a plain JS string, so no bundler needs a loader for font or CSS files,
   and DSH, which serves a plugin's client.*.js chunks only, needs no other file.
     ui/fonts/math-css.js   KaTeX's stylesheet without its @font-face rules (MIT, ui/fonts/KaTeX-LICENSE.txt). It goes with the renderer.
     ui/fonts/math-data.js  KaTeX's twenty fonts as @font-face rules with woff2 data: URIs (SIL OFL 1.1, ui/fonts/KaTeX-fonts-OFL.txt). A chunk of its
                            own, loaded when the first formula is drawn (ui/study-math-render.js), so a view that only might show one never fetches it.
   The woff and ttf fallbacks are left out (every browser that runs StudyHub reads woff2) and `font-display: block` becomes `swap`: a formula shows at
   once in the fallback serif and never holds back the page. Each string starts with its licence notice, so a saved page that embeds it carries it.
   tests/math-font.test.mjs checks that the modules never drift from this. To update: update katex, run this. */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const KATEX = new URL('../../node_modules/katex/', import.meta.url);
const FACES = 20;
const FACE = /@font-face\s*\{[^}]*\}/g;
const SOURCE = /src: url\(fonts\/([A-Za-z0-9_-]+)\.woff2\) format\("woff2"\), url\(fonts\/\1\.woff\) format\("woff"\), url\(fonts\/\1\.ttf\) format\("truetype"\);/g;
// The copyright lines of the fonts' own name tables (the same in all twenty) and of KaTeX's LICENSE.
const FONT_COPYRIGHT = 'Copyright (c) 2009-2010 Design Science, Inc.; Copyright (c) 2014-2018 Khan Academy';
const CSS_COPYRIGHT = 'Copyright (c) 2013-2020 Khan Academy and other contributors';

const minify = async (css) => (await transform(css, { loader: 'css', minify: true, legalComments: 'none' })).code.trim();
const moduleText = (header, value) => `${header}
/* GENERATED by ui/fonts/build-math-data.mjs from node_modules/katex. Do not edit. Only ui/study-math-render.js imports it. */
export default ${JSON.stringify(value)};
`;

/** The text of each generated module, by its file name in ui/fonts. */
export async function mathDataSources() {
  const { version } = JSON.parse(await readFile(new URL('package.json', KATEX), 'utf8'));
  const css = await readFile(new URL('dist/katex.css', KATEX), 'utf8');
  const faces = css.match(FACE) || [];
  const names = [...css.matchAll(SOURCE)].map((match) => match[1]);
  if (names.length !== FACES || faces.length !== FACES) throw new Error(`katex.css ${version}: expected ${FACES} faces in the known form`);
  const data = new Map(await Promise.all(names.map(async (name) => [name, (await readFile(new URL(`dist/fonts/${name}.woff2`, KATEX))).toString('base64')])));
  const fonts = faces.join('\n').replace(SOURCE, (_, name) => `src: url(data:font/woff2;base64,${data.get(name)}) format("woff2");`)
    .replace(/font-display: block;/g, 'font-display: swap;');
  // One Reserved Font Name per family, as each font's licence names it.
  const reserved = [...new Set(faces.map((face) => /font-family: "?(KaTeX_[A-Za-z0-9]+)/.exec(face)?.[1]))].sort().join(', ');
  const fontNotice = `/*! KaTeX fonts (KaTeX ${version}): ${FONT_COPYRIGHT}. SIL Open Font License 1.1, Reserved Font Names ${reserved}. */`;
  const cssNotice = `/*! KaTeX stylesheet (KaTeX ${version}): ${CSS_COPYRIGHT}. MIT License. */`;
  return {
    'math-css.js': moduleText(`/*! KaTeX ${version} stylesheet (MIT, ui/fonts/KaTeX-LICENSE.txt; ${CSS_COPYRIGHT}). */`,
      `${cssNotice}\n${await minify(css.replace(FACE, ''))}`),
    'math-data.js': moduleText(`/*! KaTeX ${version} fonts (SIL OFL 1.1, ui/fonts/KaTeX-fonts-OFL.txt; ${FONT_COPYRIGHT}; Reserved Font Names ${reserved}). */`,
      `${fontNotice}\n${await minify(fonts)}`),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [name, source] of Object.entries(await mathDataSources())) {
    await writeFile(new URL(`./${name}`, import.meta.url), source);
    console.log(`ui/fonts/${name} written (${source.length} characters)`);
  }
}
