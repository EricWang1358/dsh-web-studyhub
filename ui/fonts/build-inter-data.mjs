/* node ui/fonts/build-inter-data.mjs: writes ui/fonts/inter-data.js, the bytes of inter-latin-opsz-normal.woff2 as a data: URI, so no
   bundler (the DSH client build, the standalone preview, the demo, the many test bundles) needs a loader for font files. A test checks
   that the two never drift apart. To update Inter: replace the woff2 (and OFL.txt) from @fontsource-variable/inter, run this. */
import { readFile, writeFile } from 'node:fs/promises';

const woff2 = await readFile(new URL('./inter-latin-opsz-normal.woff2', import.meta.url));
const header = `/* GENERATED by ui/fonts/build-inter-data.mjs from inter-latin-opsz-normal.woff2 (Inter, SIL OFL 1.1: OFL.txt). Do not edit.
   The bytes of the bundled Inter as a data: URI. Its own module so the bundler gives it a chunk of its own; only ui/fonts/inter-face.js
   imports it, and only dynamically, so the host fetches it when StudyHub opens, not at activation. */
`;
await writeFile(new URL('./inter-data.js', import.meta.url), `${header}export default 'data:font/woff2;base64,${woff2.toString('base64')}';\n`);
console.log(`ui/fonts/inter-data.js written (${woff2.length} bytes of woff2)`);
